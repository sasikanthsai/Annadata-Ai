export type TKey = keyof (typeof dict)["en"];

type Ctx = { lang: Lang; setLang: (l: Lang) => void; t: (k: TKey) => string };
const I18nCtx = createContext<Ctx>({ lang: "te", setLang: () => {}, t: (k) => k });

const STORAGE_KEY = "annadata.lang";

export function I18nProvider({ children, initial = "te" }: { children: ReactNode; initial?: Lang }) {
  // Always match the server on the first render to avoid hydration mismatches;
  // the saved language is applied after hydration in useEffect.
  const [lang, setLangState] = useState<Lang>(initial);
  useEffect(() => {
    if (typeof window === "undefined") return;
    const saved = window.localStorage.getItem(STORAGE_KEY) as Lang | null;
    if (saved && saved in dict) setLangState(saved);
    const handle = (e: StorageEvent) => {
      if (e.key === STORAGE_KEY && e.newValue && e.newValue in dict) setLangState(e.newValue as Lang);
    };
    window.addEventListener("storage", handle);
    return () => window.removeEventListener("storage", handle);
  }, []);
  const value = useMemo<Ctx>(() => ({
    lang,
    setLang: (l) => setLangState(l),
    t: (k) => (dict[lang] as Record<string, string>)[k] ?? dict.en[k] ?? k,
  }), [lang]);
  return <I18nCtx.Provider value={value}>{children}</I18nCtx.Provider>;
}

export const useI18n = () => useContext(I18nCtx);

